#!/usr/bin/env python3
"""Generates Retrofy's launcher, splash, notification and in-app icons.

Every icon is drawn from the geometry below, so the adaptive vector layers
and the PNG fallbacks always match. Requires Pillow (`pip install pillow`).

    python3 scripts/generate_icons.py

Design: an orange glossy tile with a white iPod silhouette; the screen and
click wheel ring are cut out so the orange shows through, with a white
centre button.
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android" / "app" / "src" / "main" / "res"

# Adaptive icon canvas: 108 x 108 dp; launchers show the central ~72 dp and
# guarantee only the central 66 dp circle.
CANVAS = 108.0

# Silhouette, in canvas dp.
BODY = (40.0, 30.0, 68.0, 78.0)
BODY_RADIUS = 4.4
SCREEN = (43.2, 33.4, 64.8, 50.4)
SCREEN_RADIUS = 2.6
WHEEL_CENTRE = (54.0, 64.6)
WHEEL_RADIUS = 9.6
BUTTON_RADIUS = 3.7

# Background: warm orange, lighter towards the bottom, under an iOS-style
# gloss that ends in a soft curve above the middle.
GRADIENT = [(0.0, "#F4A94F"), (0.45, "#E8973D"), (1.0, "#F3BC4E")]
GLOSS_EDGE = 44.0
GLOSS_DIP = 52.0
GLOSS = [(0.0, (255, 255, 255, 150)), (1.0, (255, 255, 255, 30))]

# Legacy (pre-Android 8) icons: a rounded tile on transparency.
LEGACY_TILE = (18.0, 18.0, 90.0, 90.0)
LEGACY_RADIUS = 16.0

DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}


def _f(value: float) -> str:
    return f"{value:g}"


def _rounded_rect_path(box, r) -> str:
    l, t, rgt, b = box
    return (
        f"M{_f(l + r)},{_f(t)} H{_f(rgt - r)} "
        f"A{_f(r)},{_f(r)} 0 0 1 {_f(rgt)},{_f(t + r)} V{_f(b - r)} "
        f"A{_f(r)},{_f(r)} 0 0 1 {_f(rgt - r)},{_f(b)} H{_f(l + r)} "
        f"A{_f(r)},{_f(r)} 0 0 1 {_f(l)},{_f(b - r)} V{_f(t + r)} "
        f"A{_f(r)},{_f(r)} 0 0 1 {_f(l + r)},{_f(t)} Z"
    )


def _circle_path(cx, cy, r) -> str:
    return (
        f"M{_f(cx - r)},{_f(cy)} A{_f(r)},{_f(r)} 0 1 0 {_f(cx + r)},{_f(cy)} "
        f"A{_f(r)},{_f(r)} 0 1 0 {_f(cx - r)},{_f(cy)} Z"
    )


def silhouette_path() -> str:
    """Body with the screen and wheel ring as even-odd holes, plus the
    centre button."""
    cx, cy = WHEEL_CENTRE
    return " ".join(
        [
            _rounded_rect_path(BODY, BODY_RADIUS),
            _rounded_rect_path(SCREEN, SCREEN_RADIUS),
            _circle_path(cx, cy, WHEEL_RADIUS),
            _circle_path(cx, cy, BUTTON_RADIUS),
        ]
    )


def _vector(paths: str, size: float = CANVAS, inner: str = "") -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/generate_icons.py; edit the script instead. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        f'    android:width="{_f(size)}dp"\n'
        f'    android:height="{_f(size)}dp"\n'
        f'    android:viewportWidth="{_f(CANVAS)}"\n'
        f'    android:viewportHeight="{_f(CANVAS)}">\n'
        f"{inner}{paths}</vector>\n"
    )


def _silhouette_vector(color: str, size: float = CANVAS, scale: float = 1.0) -> str:
    path = (
        f'    <path\n        android:fillColor="{color}"\n'
        '        android:fillType="evenOdd"\n'
        f'        android:pathData="{silhouette_path()}" />\n'
    )
    if scale != 1.0:
        path = (
            f'  <group android:pivotX="54" android:pivotY="54"\n'
            f'      android:scaleX="{_f(scale)}" android:scaleY="{_f(scale)}">\n'
            f"{path}  </group>\n"
        )
    return _vector(path, size)


def _gradient_items(stops) -> str:
    return "".join(
        f'                    <item android:offset="{_f(o)}" android:color="{c}" />\n'
        for o, c in stops
    )


def background_vector() -> str:
    gloss = [(o, "#%02X%02X%02X%02X" % (a, r, g, b)) for o, (r, g, b, a) in GLOSS]
    return _vector(
        "    <path android:pathData=\"M0,0 H108 V108 H0 Z\">\n"
        "        <aapt:attr name=\"android:fillColor\">\n"
        '            <gradient android:type="linear"\n'
        '                android:startX="54" android:startY="18"\n'
        '                android:endX="54" android:endY="90">\n'
        f"{_gradient_items(GRADIENT)}"
        "            </gradient>\n"
        "        </aapt:attr>\n"
        "    </path>\n"
        f'    <path android:pathData="M0,0 H108 V{_f(GLOSS_EDGE)} '
        f'Q54,{_f(GLOSS_DIP)} 0,{_f(GLOSS_EDGE)} Z">\n'
        "        <aapt:attr name=\"android:fillColor\">\n"
        '            <gradient android:type="linear"\n'
        '                android:startX="54" android:startY="18"\n'
        f'                android:endX="54" android:endY="{_f(GLOSS_EDGE)}">\n'
        f"{_gradient_items(gloss)}"
        "            </gradient>\n"
        "        </aapt:attr>\n"
        "    </path>\n"
    )


# ---- Raster rendering (legacy launcher PNGs and the in-app icon) ----

def _hex(c: str):
    c = c.lstrip("#")
    return tuple(int(c[i : i + 2], 16) for i in (0, 2, 4))


def _lerp(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def _gradient_at(y_dp: float):
    t = min(max((y_dp - 18) / 72, 0), 1)
    stops = [(o, _hex(c)) for o, c in GRADIENT]
    for (o1, c1), (o2, c2) in zip(stops, stops[1:]):
        if t <= o2:
            return _lerp(c1, c2, (t - o1) / (o2 - o1))
    return stops[-1][1]


def _background(px: int) -> Image.Image:
    k = px / CANVAS
    img = Image.new("RGBA", (px, px))
    draw = ImageDraw.Draw(img)
    for y in range(px):
        draw.line([(0, y), (px, y)], fill=_gradient_at(y / k) + (255,))
    gloss = Image.new("RGBA", (px, px), (0, 0, 0, 0))
    mask = Image.new("L", (px, px), 0)
    # Quadratic curve from (0, edge) through control (54, dip) to (108, edge).
    points = [(0, 0), (px, 0)]
    for i in range(65):
        t = 1 - i / 64
        x = 2 * (1 - t) * t * 54 + t * t * 108
        y = (1 - t) ** 2 * GLOSS_EDGE + 2 * (1 - t) * t * GLOSS_DIP + t * t * GLOSS_EDGE
        points.append((x * k, y * k))
    ImageDraw.Draw(mask).polygon(points, fill=255)
    (r, g, b, a0), (_, _, _, a1) = GLOSS[0][1], GLOSS[1][1]
    gd = ImageDraw.Draw(gloss)
    for y in range(px):
        t = min(max((y / k - 18) / (GLOSS_EDGE - 18), 0), 1)
        gd.line([(0, y), (px, y)], fill=(r, g, b, round(a0 + (a1 - a0) * t)))
    img.alpha_composite(Image.composite(gloss, Image.new("RGBA", (px, px)), mask))
    return img


def _silhouette_mask(px: int, scale: float = 1.0) -> Image.Image:
    k = px / CANVAS * scale
    off = px / 2 - 54 * k
    m = Image.new("L", (px, px), 0)
    d = ImageDraw.Draw(m)

    def box(b):
        return [off + b[0] * k, off + b[1] * k, off + b[2] * k, off + b[3] * k]

    cx, cy = WHEEL_CENTRE
    d.rounded_rectangle(box(BODY), BODY_RADIUS * k, fill=255)
    d.rounded_rectangle(box(SCREEN), SCREEN_RADIUS * k, fill=0)
    d.ellipse(box((cx - WHEEL_RADIUS, cy - WHEEL_RADIUS, cx + WHEEL_RADIUS, cy + WHEEL_RADIUS)), fill=0)
    d.ellipse(box((cx - BUTTON_RADIUS, cy - BUTTON_RADIUS, cx + BUTTON_RADIUS, cy + BUTTON_RADIUS)), fill=255)
    return m


def render_tile(px: int, crop_to_tile: bool) -> Image.Image:
    """The full icon. [crop_to_tile] drops the adaptive canvas margin, for
    in-app use; otherwise the legacy 18 dp margin is kept."""
    ss = 8
    big = px * ss
    canvas = big if not crop_to_tile else round(big * CANVAS / 72)
    k = canvas / CANVAS
    img = _background(canvas)
    white = Image.new("RGBA", (canvas, canvas), (255, 255, 255, 255))
    img = Image.composite(white, img, _silhouette_mask(canvas))
    tile = Image.new("L", (canvas, canvas), 0)
    l, t, r, b = LEGACY_TILE
    ImageDraw.Draw(tile).rounded_rectangle(
        [l * k, t * k, r * k, b * k], LEGACY_RADIUS * k, fill=255
    )
    out = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    out = Image.composite(img, out, tile)
    if crop_to_tile:
        out = out.crop((round(l * k), round(t * k), round(r * k), round(b * k)))
    return out.resize((px, px), Image.LANCZOS)


def render_silhouette(px: int, scale: float) -> Image.Image:
    ss = 8
    mask = _silhouette_mask(px * ss, scale).resize((px, px), Image.LANCZOS)
    out = Image.new("RGBA", (px, px), (255, 255, 255, 0))
    out.putalpha(mask)
    return out


def main() -> None:
    drawable = RES / "drawable"
    (drawable / "ic_launcher_background.xml").write_text(background_vector())
    (drawable / "ic_launcher_foreground.xml").write_text(_silhouette_vector("#FFFFFF"))
    (drawable / "ic_launcher_monochrome.xml").write_text(_silhouette_vector("#FFFFFF"))
    # Android 12+ splash icon: shown inside a 160 dp circle that keeps the
    # central two thirds, so the silhouette is drawn a little smaller.
    (drawable / "splash_logo.xml").write_text(_silhouette_vector("#FFFFFF", 108, 0.82))
    # Status bar icon: white on transparency, filling its 24 dp box.
    (drawable / "ic_stat_name.xml").write_text(_silhouette_vector("#FFFFFF", 24, 2.0))

    for name, density in DENSITIES.items():
        folder = RES / f"mipmap-{name}"
        folder.mkdir(exist_ok=True)
        render_tile(round(48 * density), crop_to_tile=False).save(folder / "ic_launcher.png")

    images = ROOT / "assets" / "images"
    render_tile(512, crop_to_tile=True).save(images / "app_icon.png")
    render_silhouette(256, 2.0).save(images / "retrofy_logo.png")


if __name__ == "__main__":
    main()
